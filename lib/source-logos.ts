export function normalizeSourceLogoName(sourceName: string) {
  return sourceName
    .trim()
    .toLowerCase()
    .replace(/&/g, "and")
    .replace(/[^\w\s-]/g, " ")
    .replace(/\s+/g, "-");
}

function normalizeSourceLookupKey(sourceName: string) {
  return sourceName
    .trim()
    .toLowerCase()
    .replace(/&/g, "and")
    .replace(/[^\w\s-]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function buildArticleHeaderLogoCandidates(sourceName: string) {
  const trimmed = sourceName.trim();
  if (!trimmed) {
    return [];
  }

  const normalized = normalizeSourceLogoName(trimmed);
  const withoutLeadingThe = normalized.replace(/^the-/, "");
  const lookupKey = normalizeSourceLookupKey(trimmed);
  const candidates = new Set<string>([normalized, withoutLeadingThe]);

  if (lookupKey === "washington post" || lookupKey === "the washington post") {
    candidates.add("washington-post");
    candidates.add("the-washington-post");
  }

  if (lookupKey === "new york times" || lookupKey === "the new york times") {
    candidates.add("new-york-times");
    candidates.add("the-new-york-times");
  }

  if (lookupKey === "ap news" || lookupKey === "associated press" || lookupKey === "ap") {
    candidates.add("ap-news");
    candidates.add("ap");
  }

  return Array.from(candidates).filter(Boolean);
}

function findMappedLogoUrl(map: Record<string, string>, sourceName: string) {
  const trimmedSourceName = sourceName.trim();

  if (map[trimmedSourceName]) {
    return map[trimmedSourceName];
  }

  const normalizedLookupKey = normalizeSourceLookupKey(trimmedSourceName);
  const matchedEntry = Object.entries(map).find(
    ([candidate]) => normalizeSourceLookupKey(candidate) === normalizedLookupKey
  );

  return matchedEntry?.[1] ?? null;
}

export function slugifySourceName(sourceName: string) {
  return sourceName
    .trim()
    .toLowerCase()
    .replace(/&/g, "and")
    .replace(/[^\w\s-]/g, "")
    .replace(/\s+/g, "-");
}

export function getSourceNameFromSlug(sourceSlug: string) {
  const normalizedSlug = sourceSlug.trim().toLowerCase();
  const knownSource = Object.keys(sourceLogoMap).find(
    (sourceName) => slugifySourceName(sourceName) === normalizedSlug
  );

  if (knownSource) {
    return knownSource;
  }

  return normalizedSlug
    .split("-")
    .filter(Boolean)
    .map((segment) => segment.charAt(0).toUpperCase() + segment.slice(1))
    .join(" ");
}

export function getSourceLogoUrl(sourceName: string) {
  const trimmedSourceName = sourceName.trim();
  const mappedLogo = findMappedLogoUrl(sourceLogoMap, trimmedSourceName);

  if (mappedLogo) {
    return mappedLogo;
  }

  const normalized = normalizeSourceLogoName(trimmedSourceName);

  if (!normalized) {
    return null;
  }

  // Source logos are loaded from local assets in /public/source-logos.
  // We prefer SOURCE_LOGO_MAP for known publisher naming mismatches, then
  // fall back to a normalized filename guess. If the file is missing, the UI
  // falls back to the in-app letter badge so Reflekt never renders a broken image box.
  return `/source-logos/${normalized}.png`;
}

export function getSourceHeaderLogoUrl(sourceName: string) {
  const mappedLogo = findMappedLogoUrl(sourceHeaderLogoMap, sourceName);

  if (mappedLogo) {
    return mappedLogo;
  }

  const candidates = buildArticleHeaderLogoCandidates(sourceName);
  return candidates[0] ? `/news-logo-head/${candidates[0]}.png` : null;
}

export function getSourceHeaderDarkLogoUrl(sourceName: string) {
  const mappedLogo = findMappedLogoUrl(sourceHeaderDarkLogoMap, sourceName);

  if (mappedLogo) {
    return mappedLogo;
  }

  const candidates = buildArticleHeaderLogoCandidates(sourceName);
  return candidates[0] ? `/news-logo-head-dark/${candidates[0]}.png` : null;
}

export function getArticleHeaderLogo(
  sourceName: string,
  theme: "light" | "dark"
) {
  return theme === "dark"
    ? getSourceHeaderDarkLogoUrl(sourceName)
    : getSourceHeaderLogoUrl(sourceName);
}

export function hasMappedSourceLogo(sourceName: string) {
  return Boolean(findMappedLogoUrl(sourceLogoMap, sourceName));
}

export function getSourceBoxLogoUrl(sourceName: string) {
  return findMappedLogoUrl(sourceBoxLogoMap, sourceName);
}

export function hasMappedSourceBoxLogo(sourceName: string) {
  return Boolean(findMappedLogoUrl(sourceBoxLogoMap, sourceName));
}

export function getSourceInitial(sourceName: string) {
  return sourceName.trim().charAt(0).toUpperCase() || "N";
}
