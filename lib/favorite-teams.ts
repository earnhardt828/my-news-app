export const TEAM_PICKER_LEAGUES = ["MLB", "NFL", "NBA", "MLS", "NHL"] as const;

export type FavoriteLeagueKey = (typeof TEAM_PICKER_LEAGUES)[number];

export type FavoriteTeamOption = {
  team_id: string;
  team_name: string;
  league: FavoriteLeagueKey;
  logo_url: string | null;
};

const withLeague = (league: FavoriteLeagueKey, teamNames: string[]): FavoriteTeamOption[] =>
  teamNames.map((teamName) => ({
    team_id: `${league.toLowerCase()}-${teamName
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-+|-+$/g, "")}`,
    team_name: teamName,
    league,
    logo_url: null,
  }));

